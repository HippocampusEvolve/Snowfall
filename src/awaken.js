/**
 * awaken.js — вход в мир как пробуждение, а не как переключатель.
 *
 * Часть единой оболочки миров find-the-end.fun (docs/games.md): тот же модуль
 * с теми же ступенями стоит в Winter Tower. Различаются только три крючка,
 * которыми он держится за мир, — туман, свет и звук, — потому что устроены они
 * в мирах по-разному.
 *
 * Простая идея. Раньше вход состоял из рывков: заставка исчезала и мир
 * возникал скачком; поверх готового мира висела полупрозрачная плашка с
 * титулом, и было непонятно, внутри ты или снаружи; а после нажатия шла
 * пауза, ничем не объяснённая. Всё это время что-то честно происходило —
 * доезжала отделка, — но выглядело как затык.
 *
 * Здесь то же время обыграно. Мир проступает из темноты сквозь плотную
 * пелену; за титулом он виден, но далёк и приглушён; по нажатию пелена
 * отходит вглубь, свет набирает силу, а опущенный взгляд поднимается.
 * Ожидание никуда не делось — оно стало появлением.
 *
 * Туман здесь настоящий, а не картинка поверх кадра. `FogExp2` гасит цвет по
 * расстоянию, поэтому плотная пелена открывает сначала близкое и лишь потом
 * дальнее: она именно ОТХОДИТ вглубь, а не растворяется равномерно.
 *
 * Своё у Snowfall — цвет тумана. Он здесь и так ночной (0x0a1322), поэтому
 * пелену не нужно отдельно затемнять: достаточно плотности. В Winter Tower
 * туман дневной и светлый, и там сгущение без затемнения давало не темноту, а
 * голубую заливку во весь кадр — пришлось вести ещё и цвет.
 *
 * ГЛАВНОЕ ПРАВИЛО: длительность не зависит от того, успело ли что-то
 * загрузиться. Пробуждение идёт свои секунды всегда, а если мир к их концу ещё
 * не готов — пелена держится, пока не будет. Иначе на быстрой машине рывок
 * вернулся бы, только с другой стороны.
 *
 * ВТОРОЕ ПРАВИЛО, и оно про отклик: нажатие принимается ВСЕГДА. Раньше `enter`
 * работал только из фазы `veiled` и молча пропадал, если игрок нажал раньше,
 * чем мир проступил, — а проступает он по кадрам, которых во время сборки
 * отделки может не быть по две секунды. Снаружи это выглядело так: кнопка
 * нажата, экран входа ушёл, а лицо не поднимается и мир остаётся тёмным
 * навсегда. Теперь пробуждение начинается из ТОЙ ТОЧКИ, где застало нажатие:
 * туман и свет ведутся не от табличных значений ступени, а от текущих. Мир
 * откликается сразу, а подъём взгляда идёт свои полные секунды всегда.
 *
 * Пока идёт пробуждение, игрок не управляет ничем: он приходит в себя.
 * Поэтому цикл в это время не зовёт ни физику, ни взгляд — камерой ведёт этот
 * модуль.
 */

/** Сколько длится проявление мира из темноты за титулом. */
const REVEAL_MS = 1400;

/** Сколько длится пробуждение после нажатия. */
const WAKE_MS = 2600;

/** Во сколько раз плотнее тумана нормы: тьма и дымка за титулом. */
const FOG_DARK = 7;
const FOG_VEIL = 2.8;

/** Во сколько раз приглушён свет на тех же двух ступенях. */
const LIGHT_DARK = 0;
const LIGHT_VEIL = 0.4;

/** Насколько опущен взгляд в начале пробуждения, радианы. */
const PITCH_DOWN = -0.42;

/** На сколько взгляд отведён в сторону от того, что должен найти. */
const YAW_ASIDE = -0.17;

/** Плавность: медленно трогается, медленно останавливается. */
const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);

/** Плавность для света и звука: трогается сразу, мягко приходит. */
const easeOut = (t) => 1 - Math.pow(1 - t, 3);

const mix = (a, b, t) => a + (b - a) * t;

/**
 * @param {object} opts
 * @param {(times: number) => void} opts.setFog      во сколько раз плотнее нормы
 * @param {(mul: number) => void}    opts.setLight   1 — как задумано, 0 — черно
 * @param {(level: number) => void}  opts.setSound   1 — как задумано, 0 — тишина
 * @param {{setYaw: (yaw: number, pitch?: number) => void, yaw: number}} opts.look
 * @param {number}                   opts.yaw        куда смотреть, когда глаза открылись
 * @param {() => boolean}            [opts.ready]    готов ли мир пустить игрока
 */
export function createAwakening(opts) {
  const ready = opts.ready ?? (() => true);
  let phase = 'dark'; // dark -> reveal -> veiled -> waking -> awake
  let elapsed = 0;

  // Что стоит в кадре сейчас и что стояло в момент нажатия. Нажать могут в
  // любой момент проявления: тогда пелена отходит от того, что игрок видит,
  // а не прыгает сперва к табличной ступени.
  let curFog = FOG_DARK;
  let curLight = LIGHT_DARK;
  let curAim = 0;
  let fogAtEnter = FOG_VEIL;
  let lightAtEnter = LIGHT_VEIL;
  let aimAtEnter = 0;

  function set(fogTimes, light, sound = 0) {
    curFog = fogTimes;
    curLight = light;
    opts.setFog(fogTimes);
    opts.setLight(light);
    opts.setSound(sound);
  }

  /** Повести взгляд: t = 0 — опущен и отведён, t = 1 — на месте. */
  function aim(t) {
    curAim = t;
    // Именно `setYaw`, а не присваивание полей: кватернион камеры
    // пересобирается в `look.update`, а во время появления цикл его не зовёт.
    opts.look.setYaw(mix(opts.yaw + YAW_ASIDE, opts.yaw, t), mix(PITCH_DOWN, 0, t));
  }

  // Первый кадр рисуется в темноте и под плотной пеленой: мир уже собран, но
  // его ещё не видно. Иначе он возникает готовым, и это тот самый рывок.
  set(FOG_DARK, LIGHT_DARK);
  aim(0);

  return {
    /** Мир проступает из темноты. Зовётся на первом кадре, под заставкой. */
    reveal() {
      if (phase !== 'dark') return;
      phase = 'reveal';
      elapsed = 0;
    },

    /**
     * Игрок вошёл: пелена отходит, взгляд поднимается.
     *
     * Принимается из любой фазы до пробуждения — и из темноты, и посреди
     * проявления. Ведёт от текущего кадра, поэтому раннее нажатие не рвёт
     * картинку и не теряется.
     */
    enter() {
      if (phase === 'waking' || phase === 'awake') return false;
      // Снимок кадра, на котором нажали: от него и поведём.
      fogAtEnter = curFog;
      lightAtEnter = curLight;
      aimAtEnter = curAim;
      phase = 'waking';
      elapsed = 0;
      return true;
    },

    /**
     * Открыть мир немедленно, без появления.
     *
     * Нужен отладочному входу (`?debug`): он идёт мимо экрана входа, а значит
     * мимо `reveal` и `enter` — и мир остался бы тёмным и неуправляемым
     * навсегда. Первая же проверка на это и наткнулась.
     */
    skip() {
      set(1, 1, 1);
      aim(1);
      phase = 'awake';
    },

    /** Держит ли пробуждение управление. Пока держит — физику не трогаем. */
    holds() {
      return phase !== 'awake';
    },

    /** Вести анимацию. Зовётся каждый кадр, раньше всего остального. */
    update(dt) {
      elapsed += dt * 1000;

      if (phase === 'reveal') {
        const t = Math.min(elapsed / REVEAL_MS, 1);
        set(mix(FOG_DARK, FOG_VEIL, ease(t)), mix(LIGHT_DARK, LIGHT_VEIL, easeOut(t)));
        if (t >= 1) phase = 'veiled';
        return;
      }

      if (phase === 'waking') {
        const t = Math.min(elapsed / WAKE_MS, 1);
        // Начальные значения сняты с кадра, на котором нажали, а не взяты из
        // таблицы: иначе вход из темноты давал бы вспышку до ступени `veiled`.
        const k = ease(t);
        set(mix(fogAtEnter, 1, k), mix(lightAtEnter, 1, k), easeOut(t));
        aim(mix(aimAtEnter, 1, k));
        // Время вышло, но мир ещё не готов — держим последний кадр пелены, а
        // не отдаём управление в недособранный мир.
        if (t >= 1 && ready()) {
          set(1, 1, 1);
          aim(1);
          phase = 'awake';
        }
      }
    },
  };
}
