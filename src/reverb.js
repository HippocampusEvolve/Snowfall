// Хвост звука — место, в котором удар происходит.
//
// До сих пор каждый удар рождался и умирал в вакууме: хруст, вес — и сразу
// тишина. Так не звучит ничто. Настоящий звук оставляет после себя место:
// сперва отдельные отражения от ближних стволов или стен, потом общий гул,
// который темнеет и гаснет. По этому хвосту ухо достраивает размер и материал
// вокруг, причём раньше, чем успевает опознать сам удар.
//
// Отклик здесь считается, а не грузится файлом: готовые отклики из открытых
// библиотек звучат достовернее, но каждый — файл в сборке, лицензия в NOTICE и
// имя, которое нельзя менять из-за годового кэша. Мир остаётся без единого
// звукового файла, как и был.

// Три места. Разница между ними — не громкость, а материал: чем мягче стены,
// тем короче хвост и тем сильнее он темнеет.
//
//   лес   редкие отражения от стволов, снег съедает верх, короткий тёмный хвост;
//   дом   бревенчатая коробка: частые жёсткие отражения, хвост заметно ярче;
//   нора  вырытая в снегу пещера — почти безэховая камера. Снег лучший
//         поглотитель из всего, что есть в этом мире, и правильный ответ здесь
//         не «тихий хвост», а его отсутствие: мёртвая тишина под толщей.
const SHAPES = {
  forest: {
    seconds: 1.1,
    decay: 3.6,
    early: [
      [17, 0.34],
      [31, 0.22],
      [53, 0.14],
    ],
    damp: 0.8,
  },
  cabin: {
    seconds: 0.7,
    decay: 2.4,
    early: [
      [5, 0.6],
      [9, 0.46],
      [14, 0.38],
      [21, 0.26],
    ],
    damp: 0.5,
  },
  cave: {
    seconds: 0.32,
    decay: 5.5,
    early: [[6, 0.2]],
    damp: 0.94,
  },
};

// Сколько от звука уходит в отражения. В доме стены близко, поэтому возвращается
// заметно больше; в норе снег не возвращает почти ничего.
export const SEND = { forest: 0.18, cabin: 0.34, cave: 0.06 };

// Собрать импульсный отклик.
//
// Хвост — это шум под экспоненциальной огибающей, пропущенный через однополюсный
// фильтр, который к концу закрывается: высокие частоты в любом месте гаснут
// первыми, и без этого хвост звучит шипящей полосой, а не воздухом. Каналы
// считаются порознь: от одинакового шума слева и справа пространство
// схлопывается в точку между ушами.
export function impulseResponse(ctx, kind) {
  const s = SHAPES[kind];
  const len = Math.max(1, Math.floor(ctx.sampleRate * s.seconds));
  const buf = ctx.createBuffer(2, len, ctx.sampleRate);

  for (let c = 0; c < 2; c++) {
    const d = buf.getChannelData(c);
    let lp = 0;
    for (let i = 0; i < len; i++) {
      const k = i / len;
      const env = Math.pow(1 - k, s.decay);
      const a = 1 - s.damp * (0.35 + 0.65 * k); // место темнеет к концу хвоста
      lp += a * ((Math.random() * 2 - 1) * env - lp);
      d[i] = lp;
    }
    // Ранние отражения поверх диффузного хвоста, слева и справа со сдвигом:
    // одинаковые с обеих сторон читаются эхом в голове, а не местом вокруг.
    const skew = c === 0 ? 1 : 1.19;
    for (const [ms, gain] of s.early) {
      const at = Math.floor((ms * skew * ctx.sampleRate) / 1000);
      if (at < len) d[at] += gain * (c === 0 ? 1 : 0.88);
    }
  }
  return buf;
}
