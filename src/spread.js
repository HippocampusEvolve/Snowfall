/**
 * spread.js — раздать работу по кадрам.
 *
 * Мир одевается волнами, и каждая волна — это сотни мешей, материалов и
 * матриц, собранных подряд. Собранные подряд, они держат главный поток одной
 * задачей: у избы это доходило до 675 мс, у леса — до 619. Всё это время на
 * экране открытое меню с нарисованной, но мёртвой кнопкой: обработчик нажатия
 * просто не получает очереди.
 *
 * Лечится это не оптимизацией самих кусков (там честная работа), а дыханием:
 * между смысловыми стыками сборки поток отдаётся браузеру. Не на каждом стыке
 * — это стоило бы кадра на ровном месте, — а когда с прошлого выдоха набежал
 * бюджет кадра.
 *
 * Тот же приём, что у `warmSceneSpread` в main.js, только там порция меряется
 * объектами, а здесь стыки расставлены руками: работа внутри стыка неделима.
 */

/** Бюджет одной порции: столько мир может держать поток, не заедая меню. */
export const SPREAD_BUDGET_MS = 12;

/**
 * Сделать «выдох» для одной сборки: `await breathe()` на стыках её этапов.
 * Пока набежавшее время в бюджете — не стоит ничего и кадра не тратит.
 *
 * @param {number} [budgetMs]
 * @returns {() => Promise<void>}
 */
export function createSpread(budgetMs = SPREAD_BUDGET_MS) {
  let since = performance.now();
  return function breathe() {
    if (performance.now() - since < budgetMs) return Promise.resolve();
    return new Promise((resolve) =>
      requestAnimationFrame(() => {
        since = performance.now();
        resolve();
      })
    );
  };
}
