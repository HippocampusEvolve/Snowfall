import { makeSet } from 'world-core/materials';

// Наборы карт ядра — по одному на игру.
//
// Набор считается ОДИН раз и раздаётся всем, кому нужен: `material()` в ядре
// клонирует текстуры ради своего числа повторов, и клон ничего не стоит — three
// держит объект видеокарты в кэше по картинке плюс параметрам сэмплера, а
// `repeat` в ключ кэша не входит.
//
// Отдельный модуль появился, когда за одними и теми же наборами пришли двое:
// нутро топки (`firebox.js`) и сам камин с брусом полки (`cabin.js`). Два
// собственных кэша означали бы две выпечки одного кирпича — по полсекунды и по
// три карты 512x512 в видеопамяти каждая.

const cache = new Map();

/** Набор карт по имени рецепта ядра. Считается при первом спросе. */
export function matset(name) {
  let s = cache.get(name);
  if (!s) {
    s = makeSet(name);
    cache.set(name, s);
  }
  return s;
}

/** Посчитать сразу несколько и отдать объектом: `sets('brick', 'beam').brick`. */
export function matsets(...names) {
  const out = {};
  for (const n of names) out[n] = matset(n);
  return out;
}
