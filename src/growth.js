// Живой мир: что случилось, пока игрока не было.
//
// Модуль намеренно пустой на побочные действия - только чистые функции от
// прошедшего времени в секундах. Никаких таймеров «пока игрока нет» не
// существует: мир досчитывается ОДИН раз при загрузке, из разницы между
// сейчасом и временем записи (или временем последнего сохранения). Так
// отсутствие любой длины стоит одинаково дёшево, а вкладка, оставленная
// открытой на ночь, не отличается от закрытой.
//
// Отсюда же следует, что во время игры формулы не меняются: горение костра,
// рубка и копание живут в своих модулях, здесь только «дорисовка» пропуска.
// three не импортируется - модуль обязан ехать на голом Node в тестах.

// Пень стоит два часа: короче - и вернувшийся через обед не узнал бы поляну,
// где валил лес; дольше - и вмятина от ствола перестаёт читаться как след
// работы, превращаясь в пустое место.
export const REGROW_YOUNG = 2 * 3600;
// Сутки - шаг, за который лес заметно меняется, но не подменяется: на месте
// вчерашнего пня хлыстик, а не готовая сосна.
export const REGROW_GROWN = 24 * 3600;
// Трое суток - полный оборот: ушёл на выходные, вернулся в целый лес.
export const REGROW_ADULT = 72 * 3600;
// Зарубки затягиваются за те же сутки: недорубленное дерево ждёт ровно день,
// дальше начинать приходится сначала.
export const HEAL_HITS = 24 * 3600;
// Костёр без хозяина прогорает медленнее, чем на глазах (FUEL_TIME = 480 с):
// два часа от полного до углей. Быстрее - и возвращаться было бы не к чему,
// медленнее - и топить стало бы незачем.
export const FUEL_TIME_AWAY = 2 * 3600;
// Постоянная затухания троп: за полсуток от следа остаётся треть, за двое
// суток - ничего. Метель на поляне заметает вечернюю тропу к утру.
export const TRAIL_TAU = 12 * 3600;
// Яма живёт втрое дольше тропы: снег ссыпается с краёв, но не залечивает
// раскоп за ночь. Трое суток - две трети ямы.
export const PIT_TAU = 72 * 3600;
// Глубже полутора метров снег со стенок уже не достаёт: тоннели и пещеры
// остаются как выкопаны, затягивает только ямы у поверхности.
export const PIT_DEPTH = 1.5;

/**
 * Стадия отросшей сосны по возрасту сруба (с).
 *
 * 'stump' - инстанс скрыт, на месте вмятина; 'young' - хлыстик 0.35 без
 * коллайдера; 'grown' - половинная сосна 0.7 с коллайдером; 'adult' - как
 * новая. Границы включают левый край: ровно в два часа уже 'young'.
 */
export function regrowStage(age) {
  if (!(age >= REGROW_YOUNG)) return 'stump'; // NaN и отрицательное - тоже пень
  if (age < REGROW_GROWN) return 'young';
  if (age < REGROW_ADULT) return 'grown';
  return 'adult';
}

/** Масштаб инстанса для стадии. 0 у пня: нулевая матрица прячет сосну. */
export function regrowScale(stage) {
  if (stage === 'young') return 0.35;
  if (stage === 'grown') return 0.7;
  return stage === 'adult' ? 1 : 0;
}

/** Зарубки на стоящей сосне: зарастают линейно за сутки, до целого. */
export function healedHits(hits, age) {
  if (!(age > 0)) return hits;
  if (age >= HEAL_HITS) return 0;
  return Math.max(0, Math.round(hits * (1 - age / HEAL_HITS)));
}

/** Топливо костра после отсутствия. Ниже нуля не уходит: остаются угли. */
export function fuelAfter(fuel, away) {
  if (!(away > 0)) return fuel;
  return Math.max(0, fuel - away / FUEL_TIME_AWAY);
}

/** Во сколько раз побледнели тропы. */
export function trailFade(away) {
  if (!(away > 0)) return 1;
  return Math.exp(-away / TRAIL_TAU);
}

/** Во сколько раз осела правка снега у поверхности. */
export function pitFill(away) {
  if (!(away > 0)) return 1;
  return Math.exp(-away / PIT_TAU);
}
