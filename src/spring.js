// Критически задемпфированная пружина, считаемая ТОЧНО.
//
// Такая пружина стоит под каждым телесным откликом: отдача камеры от удара
// (tool.js), клевок взгляда при приземлении (look.js), просадка рук
// (viewmodel.js). Уравнение у всех одно: x'' = -w²·x - 2w·x' — приходит к нулю
// без отскока.
//
// Считать его пошагово (v += (-w²x - 2w·v)·dt; x += v·dt) нельзя, и это не
// вкусовщина. Так было, и вот чем это оборачивалось при потолке шага 0.05 с:
//
//   отдача копки, w = 18, импульс 1.7
//     60 кадр/с   должно 1.98°   получалось 0.85°   вдвое слабее задуманного
//     30 кадр/с   должно 1.96°   получалось 0.65°
//     20 кадр/с   должно 1.98°   получалось  436°   камеру швыряет
//
// То есть схема врала ВСЕГДА: на ровных кадрах отдача выходила вдвое слабее
// той, что записана в замахах, а начиная с 21 кадра в секунду шла вразнос.
// Потолок dt = 0.05 от этого не спасает — он лежит внутри зоны расхождения
// (порог 0.047). Winter Tower поймал это замером на живом сервере: пик отдачи
// от одного удара лопатой 0.82 рад, то есть 47°.
//
// Здесь вместо шага берётся решение уравнения в лоб:
//   x(t) = (x₀ + (v₀ + w·x₀)·t)·e^(−w·t)
// Оно верно при любом dt, и на большом шаге даёт не взрыв, а просто более
// быстрое затухание. Пик перестаёт зависеть от частоты кадров вовсе.
//
// Этот файл — первый кусок общего ядра миров (world-core): в Winter Tower он
// уже есть под именем spring.ts, слово в слово.

/**
 * Продвинуть пружину на dt.
 * @param {{x: number, v: number}} s состояние: смещение и скорость
 * @param {number} w жёсткость, 1/с (полное оседание ≈ 4/w)
 * @param {number} dt шаг, с
 */
export function stepSpring(s, w, dt) {
  const b = s.v + w * s.x;
  const e = Math.exp(-w * dt);
  s.x = (s.x + b * dt) * e;
  s.v = (s.v - w * b * dt) * e;
}
