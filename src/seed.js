// Семя мира. Одно число, от которого детерминированно раскладывается всё
// процедурное: пока это поле пещер (caves.js), дальше - рассев камней и кустов.
// Лес живёт на своём FOREST_SEED (trees.js) с более ранних времён; сводить их
// в одно число можно только вместе с пересевом леса, а он уже стоит в мирах
// игроков.
export const WORLD_SEED = 20260902; // день, когда под миром появились пещеры

/** Детерминированный генератор: одно 32-битное семя, поток чисел [0,1). */
export function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
