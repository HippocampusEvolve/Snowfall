import { box, cyl } from './parts.js';

// Лопата: черенок, тулейка, штык.
//
// Конвенция рига (HeldTool, см. shovel.js): ОСТРИЁ ШТЫКА В НАЧАЛЕ КООРДИНАТ,
// черенок вверх по +Y, совок открыт в -Z, высота 1.45 м. По этой конвенции
// выставлены кейфреймы замахов, точка хвата и остриё в покое, поэтому её
// нельзя двигать - от неё зависит вся анимация в руках.
//
// Штык не плоская пластина: три дощечки, средняя прямо, две крыла довёрнуты
// внутрь - выходит гранёный совок с вогнутой стороной к -Z. Гранёная форма
// здесь не бедность, а язык мира: так же собраны кирка и топор.

export const HEIGHT = 1.45;
/** Ширина штыка - по ней меряется полоса снега, что лопата берёт за раз. */
export const BLADE_W = 0.2;

const SHAFT_R_TOP = 0.019;
const SHAFT_R_BOTTOM = 0.022;

export function shovelParts() {
  return [
    // ---- штык ----
    // средняя дощечка: книзу сходит к острию
    box('steel', 0.104, 0.245, 0.011, 0, 0.1225, -0.0245, {
      taper: { axis: 'y', x: [0.42, 1] },
    }),
    // крылья: довёрнуты внутрь, вогнутой стороной в -Z
    box('steel', 0.062, 0.245, 0.010, 0.0697, 0.1225, -0.0175, {
      rot: [0, -0.42, 0],
      taper: { axis: 'y', x: [0.42, 1] },
    }),
    box('steel', 0.062, 0.245, 0.010, -0.0697, 0.1225, -0.0175, {
      rot: [0, 0.42, 0],
      taper: { axis: 'y', x: [0.42, 1] },
    }),
    // подножка: закатанная верхняя кромка штыка, на неё давят ногой
    cyl('steel', 0.011, 0.011, 0.185, 6, 0, 0.2435, -0.0205, { rot: [0, 0, Math.PI / 2] }),

    // ---- тулейка ----
    // конус от штыка к черенку; сидит на кромке, слегка отклонён назад
    cyl('steel', 0.022, 0.033, 0.22, 8, 0, 0.333, -0.011),

    // ---- черенок ----
    cyl('wood', SHAFT_R_TOP, SHAFT_R_BOTTOM, 1.0, 8, 0, 0.925, -0.002),
    // Т-образная рукоять: перекладина поперёк и две щёчки под ней
    cyl('wood', 0.016, 0.016, 0.15, 8, 0, 1.434, -0.002, { rot: [0, 0, Math.PI / 2] }),
    box('wood', 0.026, 0.09, 0.022, 0.037, 1.383, -0.002, { rot: [0, 0, -0.28] }),
    box('wood', 0.026, 0.09, 0.022, -0.037, 1.383, -0.002, { rot: [0, 0, 0.28] }),
  ];
}
