import { lathe, cyl, torus } from './parts.js';

// Котелок: чугунное пузатое тело, крышка и дужка.
//
// Стоит донцем на нуле, дужка поднята - за неё котелок снимают с огня. Дужка
// не выше габарита тела: поднятая до полного полукруга, она задирала бы верх
// предмета на треть, и котелок перестал бы влезать под полку у очага.
//
// Тело - тело вращения: у чугунка вся форма в профиле, и двенадцати граней по
// кругу хватает, чтобы силуэт читался круглым, а рёбра работали как отблески
// на литье.

const SEG = 12;
/** Профиль тела: [радиус, высота]. Донце узкое, пузо широкое, горло уже пуза. */
const BODY = [
  [0.000, 0.000],
  [0.082, 0.000],
  [0.112, 0.022],
  [0.145, 0.098],
  [0.138, 0.172],
  [0.117, 0.202],
  [0.127, 0.220],
];

const RIM = BODY[BODY.length - 1][1]; // верх венчика
/** Ушки дужки сидят на пузе - отсюда она и качается. */
const BAIL_Y = 0.176;
const BAIL_R = 0.115;

export function potParts() {
  return [
    lathe('iron', BODY, SEG, 0, 0, 0, { uv: 1.5 }),
    // крышка с бортиком и шишечкой
    cyl('iron', 0.100, 0.119, 0.020, SEG, 0, RIM + 0.011, 0, { uv: 2 }),
    cyl('iron', 0.014, 0.019, 0.028, 6, 0, RIM + 0.035, 0, { uv: 2 }),
    // дужка: полукольцо прутка, плоскостью поперёк комнаты
    torus('iron', BAIL_R, 0.008, 5, 10, Math.PI, 0, BAIL_Y, 0, { uv: 4 }),
  ];
}
