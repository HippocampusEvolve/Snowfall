// Кострище: кольцо камней и зола внутри.
//
// Камни разной породы и разного размера, каждый мятый своим масштабом и
// повёрнут своим углом - икосаэдр без подразбиения даёт ровно ту гранёную
// колотую форму, что нужна булыжнику. Раскладка ЗАШИТА ЧИСЛАМИ, а не считается
// случайностью: костёр в мире один, и он должен выглядеть одинаково в каждом
// заходе и в каждой проверке.
//
// Просвет кладки - 0.372 м: по нему меряется зола и полотно пламени
// (campfire.js). Камни стоят на кольце радиуса RING, внутрь заходят не глубже
// этого просвета.
export const RING = 0.5;
/** Просвет кладки: внутрь этого круга камни не заходят. */
