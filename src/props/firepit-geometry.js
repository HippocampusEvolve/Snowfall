// Половина высоты икосаэдра three: его вершины лежат на сфере, и по каждой
// оси габарит выходит в 0.8507 радиуса, а не в радиус.
const ICO_HALF = 0.8506508;

function stone(role, [a, ring, r, scale, rot, sink]) {
  const y = ICO_HALF * r * scale[1] - sink;
  return ico(role, r, Math.cos(a) * ring, y, Math.sin(a) * ring, { scale, rot, uv: 1.6 });
}

export function firepitParts() {
  return [
    ...STONES.map((s) => stone('rubble', s)),
    ...CHIPS.map((s) => stone('rubble', s)),
    // Зола внутри кольца: плоский диск чуть выше земли. Радиус равен просвету
    // кладки минус миллиметр - шире он прошёл бы сквозь камни и замерцал.
    cyl('ash', CLEARANCE - 0.012, CLEARANCE - 0.012, 0.012, 24, 0, 0.012, 0, { uv: 1 }),
  ];
}
